// Redirect login contract: browser navigation only; no Telegram popup or real identity provider.
import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const source=fs.readFileSync(new URL('../../web/website.js',import.meta.url),'utf8');
function trial({host='lunar-api.solb7403.workers.dev',origin='https://lunar-api.solb7403.workers.dev',search='',target='garage'}={}){
 const calls=[],notices=[],notice={hidden:true,textContent:'',append(){}},listeners={};
 const location={hostname:host,origin,search,hash:'',assign:u=>calls.push(['navigate',u])};
 const window={history:{replaceState:(...args)=>calls.push(['history',...args])}};
 const document={querySelector:s=>s==='#login-status'?notice:null,createElement:()=>({setAttribute(){}}),addEventListener:(k,fn)=>listeners[k]=fn};
 const context={location,URLSearchParams,document,window,sessionStorage:{setItem:(k,v)=>calls.push(['ref',k,v])}};
 vm.createContext(context);vm.runInContext(source,context);
 window.lunarLogin(target);
 return {calls,notice,listeners};
}
assert.equal(trial().calls[0][1],'/web/login.html#garage');
assert.equal(trial({target:'mode:arena'}).calls[0][1],'/web/login.html#mode:arena');
assert.equal(trial({target:'https://evil.test'}).calls[0][1],'/web/login.html#play');
// a squad invite code (?i=, server-issued) is forwarded to the official origin; a bare pilot id (?ref=) is not
const gh=trial({host:'solb7403-creator.github.io',origin:'https://solb7403-creator.github.io',search:'?i=ABCD2345'});
assert.equal(gh.calls.find(c=>c[0]==='navigate')[1],'https://lunar-api.solb7403.workers.dev/web/?i=abcd2345#garage');
const old=trial({host:'solb7403-creator.github.io',origin:'https://solb7403-creator.github.io',search:'?ref=tg_123456'});
assert.equal(old.calls.find(c=>c[0]==='navigate')[1],'https://lunar-api.solb7403.workers.dev/web/#garage');
const failed=trial({search:'?login=exchange'});
assert.match(failed.notice.textContent,/could not complete/i);
assert.equal(failed.calls.find(c=>c[0]==='history')[3],'/web/');
assert.equal(source.includes('Telegram.Login.auth'),false,'must not depend on popup communication');
assert.equal(source.includes('telegram-login.js'),false,'no popup login SDK loaded');
const loginPage=fs.readFileSync(new URL('../../web/login.html',import.meta.url),'utf8');
const loginScript=fs.readFileSync(new URL('../../web/login.js',import.meta.url),'utf8');
for(const id of ['login-status','open-bot','manual','login-command','copy-code','retry-login'])assert.match(loginPage,new RegExp('id="'+id+'"'));
assert.match(loginScript,/auth\/bot\/start/);
assert.match(loginScript,/auth\/bot\/finish/);
assert.match(loginScript,/\/web\/play\.html#/);
assert.match(loginScript,/visibilitychange/);
assert.equal(loginScript.includes('Telegram.Login.auth'),false);
assert.equal(loginPage.includes('telegram-login.js'),false);
const accountPage=fs.readFileSync(new URL('../../web/account.html',import.meta.url),'utf8');
const accountScript=fs.readFileSync(new URL('../../web/account.js',import.meta.url),'utf8');
const gamePage=fs.readFileSync(new URL('../../web/play.html',import.meta.url),'utf8');
// call sign + password is the main way in; passkey/Telegram/Google are optional alternatives
for(const id of ['signup-form','su-cs','su-pw','su-go','login-form','li-cs','li-pw','li-keep','forgot-open','forgot-form','passkey-btn','start-telegram','start-google','existing-account','switch-account'])assert.match(loginPage,new RegExp('id="'+id+'"'),id);
assert.match(loginPage,/id="su-cs"[^>]*autocomplete="username"/,'call sign is the username for password managers');
assert.match(loginPage,/id="su-pw"[^>]*type="password"[^>]*autocomplete="new-password"/);
assert.match(loginPage,/id="li-pw"[^>]*autocomplete="current-password"/);
assert.match(loginPage,/id="li-keep" type="checkbox" checked/,'keep me signed in on by default');
assert.match(loginPage,/id="passkey-btn"[^>]*hidden/,'passkey hidden unless the device supports it');
assert.match(loginPage,/By playing you agree to the <a href="\/terms.html"[^>]*>Terms<\/a> and <a href="\/privacy.html"/);
assert.doesNotMatch(loginPage+loginScript,/security key/i,'never say "security key"');
const signupForm=loginPage.slice(loginPage.indexOf('<form id="signup-form"'),loginPage.indexOf('</form>',loginPage.indexOf('<form id="signup-form"')));
assert.doesNotMatch(signupForm,/confirm.?password|captcha|type="email"|e-?mail/i,'no confirm-password, captcha or email at signup');
assert.equal((signupForm.match(/<input /g)||[]).length,2,'two fields: call sign and password');
for(const path of ['/auth/acct/signup','/auth/acct/login','/auth/acct/check','/auth/lunar/register/options','/auth/lunar/login/options'])assert.ok(loginScript.includes(path),path);
assert.match(loginScript,/isUserVerifyingPlatformAuthenticatorAvailable/,'passkey only offered where the device can make one');
assert.match(loginScript,/lunar-invite/,'invite kept through signup');
assert.match(accountScript,/\/auth\/lunar\/link\/start/);
assert.match(accountScript,/\/auth\/lunar\/link\/status/);
for(const p of ['/auth/acct/password','/auth/acct/logout-all','/auth/acct/delete','/auth/acct/email','/auth/lunar/addkey/options'])assert.ok(accountScript.includes(p),p);
assert.match(accountPage,/Used only to reset your password\. Without a recovery method, a forgotten password means your account is lost permanently\./);
assert.match(gamePage,/href="web\/account\.html"/);
assert.match(gamePage,/manifest\.webmanifest/);
const manifest=JSON.parse(fs.readFileSync(new URL('../../web/manifest.webmanifest',import.meta.url),'utf8'));
assert.equal(manifest.display,'standalone');assert.ok(manifest.icons.some(i=>i.sizes==='512x512')&&manifest.icons.some(i=>i.sizes==='192x192'));
assert.ok(fs.existsSync(new URL('../../privacy.html',import.meta.url)),'privacy policy page');
console.log('PASS call sign + password entry, optional passkey/Telegram/Google, settings, manifest, privacy');
