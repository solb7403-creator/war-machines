import assert from 'node:assert/strict';
import {buildSim} from '../../../worker/build-sim.mjs';
import {fakeRec} from './fakerec.mjs';
buildSim();
const {RULES:R}=await import('../../../worker/src/sim.gen.js');
const {checkProof}=await import('../../../worker/src/proof.js');
const {RoomCore}=await import('../../../worker/src/pvp.js');
const ctx={g:'arena',m:'1v1',map:'classic',secs:70,won:true,drawn:false,place:0,series:true,min:12,spdM:1,st:{dmg:0},variants:[{ci:1,mhp:1700,spdM:1}]};
const pf=fakeRec({dur:60,won:true});
assert.equal(checkProof(pf,ctx).ok,true);
const forged=structuredClone(pf);forged.h[0][1]=0;
assert.equal(checkProof(forged,ctx).ok,false,'unowned chassis in frozen proof rejected');
const injected=structuredClone(pf);injected.cs=[[4,0]];
assert.equal(checkProof(injected,ctx).ok,false,'midfight chassis switch rejected');
const forgedPhase=structuredClone(pf);forgedPhase.cs=[[4,0]];
const bytes=Buffer.from(forgedPhase.s,'base64');bytes[4*(pf.n*3+6)+pf.n*3+2]|=64;forgedPhase.s=bytes.toString('base64');
assert.equal(checkProof(forgedPhase,{...ctx,variants:[...ctx.variants,{ci:0,mhp:1360,spdM:1.25}]}).ok,false,'a round flag alone cannot authorize chassis swap');
// A legitimate pre-round class is checked against owned frozen variants.
const scout=structuredClone(pf);scout.h[0][1]=0;scout.h[0][2]=1360;
assert.equal(checkProof(scout,{...ctx,variants:[...ctx.variants,{ci:0,mhp:1360,spdM:1.25}]}).ok,true);
let L=structuredClone(R.STOCK_L);L.chs=[{c:'vanguard',t:0,q:1,s:false},{c:'scout',t:0,q:1,s:false}];
const io={now:()=>1000,day:()=>20000,setTimeout:()=>0,clearTimeout(){},setInterval:()=>0,clearInterval(){},ev(){}};
const room=new RoomCore(io,{MAP:'classic'});
room.seatPlayer({pid:'tg_1',name:'One',q:{g:'arena',m:'1v1'},L,power:R.powerOf(L),league:0});
L.up.hull=4;
assert.equal(room.seats[0].L.up.hull,0,'room owns a detached snapshot');
assert.deepEqual(room.seats[0].L.chs,[room.seats[0].L.c],'Room contains only registered machine');
room.seatPlayer({pid:'tg_1',name:'One',q:{g:'arena',m:'1v1'},L,power:999,league:4});
assert.equal(room.seats[0].L.up.hull,0,'join retry cannot replace queued equipment');
room.startVs();
assert.deepEqual(room.goMsg(room.seats[0]).chs,['vanguard'],'Only the selected machine is exposed to PvP');
const socket={send(){},close(){}};room.connect('tg_1',socket);
room.onMessage('tg_1',socket,JSON.stringify({k:'c',c:'scout'}));
assert.equal(room.sim.units[0].cls,'vanguard','legacy inventory switch is rejected');
assert.equal(room.sim.units[0].mhp,1700,'failed switch cannot alter combat stats');
assert.equal(room.seats[0].L.c.c,'vanguard','seat snapshot is immutable to switch requests');
console.log('PASS frozen proof variants and locked PvP battle roster');
