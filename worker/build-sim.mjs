// Builds worker/src/sim.gen.js: the game's own sim (js/rules.js + js/game.js) wrapped in createSim(),
// so every live match gets its own copy, plus worker/sim-api.js (what the room calls).
// Run by the deploy workflow and the tests; the output is not committed.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url)), repo = join(here, '..');
export function buildSim(out = join(here, 'src', 'sim.gen.js')) {
  const read = (f) => readFileSync(join(repo, f), 'utf8').replace(/^'use strict';[^\n]*\n/m, '');
  // RULES: everything rules.js declares (found by running it), for server code that needs the rules but no sim
  const rules = read('js/rules.js'), ctx = vm.createContext({}), bare = vm.createContext({});
  vm.runInContext(rules, ctx);
  const names = [...new Set(rules.match(/\b[A-Za-z_$][\w$]*\b/g))].filter((n) => {
    try { return vm.runInContext('typeof ' + n, ctx) !== 'undefined' && vm.runInContext('typeof ' + n, bare) === 'undefined'; } catch (e) { return false; }
  });
  const src = '// GENERATED by worker/build-sim.mjs from js/rules.js, js/game.js and worker/sim-api.js. Edit those, not this.\n' +
    'export const RULES = (function () {\n"use strict";\n' + rules + 'return { ' + names.join(', ') + ' };\n})();\n' +
    'export function createSim(HOST) {\n"use strict";\n' +
    '// ===== js/rules.js =====\n' + read('js/rules.js') +
    '// ===== js/game.js =====\n' + read('js/game.js') +
    '// ===== worker/sim-api.js =====\n' + read('worker/sim-api.js') + '}\n';
  writeFileSync(out, src);
  return out;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) console.log('wrote', buildSim());
